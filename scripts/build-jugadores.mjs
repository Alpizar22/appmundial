function rosterFor(pais, count) {
  const seeds = DESTACADOS[pais] || []
  const out = []
  for (let i = 0; i < count; i++) {
    if (i < seeds.length) out.push(seeds[i])
    else out.push(`Plantel ${i + 1} · ${pais}`)
  }
  return out
}

const entries = []
for (let t = 0; t < nTeams; t++) {
  const pais = ORDEN[t]
  const count = counts[t]
  const names = rosterFor(pais, count)
  for (const nombre of names) entries.push({ pais, nombre })
}

if (entries.length !== TOTAL) {
  console.error('Expected', TOTAL, 'got', entries.length)
  process.exit(1)
}

